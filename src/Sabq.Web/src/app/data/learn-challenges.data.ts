export interface LearnChallengeQuestion {
  id: string;
  prompt: string;
  choices: readonly string[];
  correctChoiceIndex: number;
  explanation: string;
}

export interface LearnChallengeSource {
  title: string;
  publisher: string;
  url: string;
}

export interface LearnChallengePack {
  slug: string;
  title: string;
  summary: string;
  introduction: string;
  learningGoals: readonly string[];
  estimatedMinutes: number;
  publishedAt: string;
  updatedAt: string;
  reviewerName: string;
  reviewMethod: string;
  questions: readonly LearnChallengeQuestion[];
  sources: readonly LearnChallengeSource[];
}

type PackInput = Omit<LearnChallengePack, 'questions'> & { questions: readonly LearnChallengeQuestion[] };

function question(
  id: string,
  prompt: string,
  choices: readonly string[],
  correctChoiceIndex: number,
  explanation: string
): LearnChallengeQuestion {
  return { id, prompt, choices, correctChoiceIndex, explanation };
}

function pack(input: PackInput): LearnChallengePack {
  if (input.questions.length !== 10) {
    throw new Error(`حزمة التعلم ${input.slug} يجب أن تضم 10 أسئلة بالضبط.`);
  }

  return input;
}

